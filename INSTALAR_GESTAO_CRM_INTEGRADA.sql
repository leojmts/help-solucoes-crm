create or replace function public.atualizar_total_proposta()
returns trigger language plpgsql security invoker set search_path = '' as $$
declare v_id uuid;
begin
  v_id := coalesce(new.proposta_id, old.proposta_id);
  update public.propostas_comerciais p
  set valor_total = greatest(0, coalesce((select sum(i.quantidade*i.valor_unitario) from public.proposta_itens i where i.proposta_id=v_id and not i.recorrente),0)-p.desconto),
      valor_mensal = coalesce((select sum(i.quantidade*i.valor_unitario) from public.proposta_itens i where i.proposta_id=v_id and i.recorrente),0),
      atualizado_em = now()
  where p.id=v_id;
  return coalesce(new,old);
end $$;

