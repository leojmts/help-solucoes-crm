for each row execute function public.atualizar_total_proposta();

create or replace function public.movimentar_saldo_estoque()
returns trigger language plpgsql security invoker set search_path = '' as $$
declare v_atual numeric; v_novo numeric;
begin
  select quantidade into v_atual from public.estoque_itens where id=new.item_id for update;
  if v_atual is null then raise exception 'Item de estoque não encontrado.'; end if;
  v_novo := v_atual + case when new.direcao='Entrada' then new.quantidade else -new.quantidade end;
  if v_novo < 0 then raise exception 'Saldo insuficiente no estoque.'; end if;
  update public.estoque_itens set quantidade=v_novo,
    custo_medio=case when new.direcao='Entrada' and new.custo_unitario is not null then new.custo_unitario else custo_medio end,
    atualizado_em=now() where id=new.item_id;
  return new;
end $$;

