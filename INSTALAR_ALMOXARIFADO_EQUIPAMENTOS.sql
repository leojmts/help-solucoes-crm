create or replace function public.validar_estado_emprestimo_equipamento()
returns trigger language plpgsql security invoker set search_path='' as $$
declare v_ativo boolean;
begin
  select exists(
    select 1 from public.equipamento_emprestimos
    where equipamento_id=new.id and status in ('Ativo','Aguardando devolução')
  ) into v_ativo;
  if (new.emprestado or new.status='Emprestado') and not v_ativo then
    raise exception 'Use a ação Emprestar reserva para marcar uma máquina como emprestada.';
  end if;
  if v_ativo and (not new.emprestado or new.status<>'Emprestado') then
    raise exception 'Receba a devolução antes de alterar o estado desta máquina.';
  end if;
  return new;
end $$;

