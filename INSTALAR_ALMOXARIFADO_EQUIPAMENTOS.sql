create or replace function public.salvar_cliente_unidade(
  p_id bigint, p_cliente_id bigint, p_nome text, p_cidade text, p_uf text,
  p_endereco text, p_principal boolean, p_ativo boolean
)
returns bigint language plpgsql security invoker set search_path='' as $$
declare v_id bigint;
begin
  if (select auth.uid()) is null or not (private.crm_tem_permissao('crm') or private.crm_tem_permissao('osCriar') or private.crm_tem_permissao('osEditar')) then
    raise exception 'Você não possui permissão para alterar filiais.' using errcode='42501';
  end if;
  if nullif(btrim(p_nome),'') is null then raise exception 'Informe o nome da filial.'; end if;
  if coalesce(p_principal,false) then update public.cliente_unidades set principal=false,atualizado_em=now() where cliente_id=p_cliente_id and id is distinct from p_id; end if;
  if p_id is null then
    insert into public.cliente_unidades(cliente_id,nome,cidade,uf,endereco,principal,ativo,criado_por)
    values(p_cliente_id,btrim(p_nome),coalesce(btrim(p_cidade),''),upper(coalesce(btrim(p_uf),'')),coalesce(btrim(p_endereco),''),coalesce(p_principal,false),coalesce(p_ativo,true),(select auth.uid()))
    returning id into v_id;
  else
    update public.cliente_unidades set nome=btrim(p_nome),cidade=coalesce(btrim(p_cidade),''),uf=upper(coalesce(btrim(p_uf),'')),endereco=coalesce(btrim(p_endereco),''),principal=coalesce(p_principal,false),ativo=coalesce(p_ativo,true),atualizado_em=now()
    where id=p_id and cliente_id=p_cliente_id returning id into v_id;
    if v_id is null then raise exception 'Filial não encontrada ou sem permissão.'; end if;
  end if;
  return v_id;
end $$;

create or replace function public.movimentar_equipamento(
  p_equipamento_id bigint, p_tipo text, p_origem text, p_destino text,
  p_cliente_id bigint, p_unidade_id bigint, p_os_id bigint, p_status_novo text,
  p_responsavel_nome text, p_condicao text, p_acessorios text, p_descricao text
)
returns bigint language plpgsql security invoker set search_path='' as $$
declare e public.equipamentos%rowtype; v_mov bigint; v_cliente_nome text;
begin
  if (select auth.uid()) is null or not (private.crm_tem_permissao('osCriar') or private.crm_tem_permissao('osEditar')) then
    raise exception 'Você não possui permissão para movimentar equipamentos.' using errcode='42501';
  end if;
  select * into e from public.equipamentos where id=p_equipamento_id for update;
  if not found then raise exception 'Equipamento não encontrado.'; end if;
  if e.emprestado then raise exception 'Este equipamento possui empréstimo ativo. Finalize a devolução antes de movimentá-lo.'; end if;
  select nome into v_cliente_nome from public.clientes where id=p_cliente_id;
  update public.equipamentos set
    cliente_id=p_cliente_id, cliente_nome=coalesce(v_cliente_nome,case when e.proprietario_tipo='Help' then 'Estoque interno' else e.cliente_nome end),
    unidade_id=p_unidade_id, localizacao=coalesce(nullif(btrim(p_destino),''),localizacao),
    status=coalesce(nullif(btrim(p_status_novo),''),status), responsavel_nome=coalesce(btrim(p_responsavel_nome),''),
    condicao=coalesce(nullif(btrim(p_condicao),''),condicao), acessorios=coalesce(btrim(p_acessorios),''), atualizado_em=now()
  where id=e.id;
  insert into public.equipamento_movimentacoes(equipamento_id,cliente_id,unidade_id,os_id,tipo,origem,destino,status_anterior,status_novo,responsavel_nome,condicao,acessorios,descricao,usuario_id)
  values(e.id,p_cliente_id,p_unidade_id,p_os_id,btrim(p_tipo),coalesce(btrim(p_origem),''),coalesce(btrim(p_destino),''),e.status,coalesce(nullif(btrim(p_status_novo),''),e.status),coalesce(btrim(p_responsavel_nome),''),coalesce(btrim(p_condicao),''),coalesce(btrim(p_acessorios),''),coalesce(btrim(p_descricao),''),(select auth.uid()))
  returning id into v_mov;
  return v_mov;
end $$;

create or replace function public.registrar_emprestimo_equipamento(
  p_equipamento_id bigint, p_cliente_id bigint, p_unidade_id bigint, p_os_id bigint,
  p_responsavel_nome text, p_previsao_devolucao date, p_motivo text,
  p_condicao_saida text, p_acessorios_saida text, p_observacoes text
)
returns bigint language plpgsql security invoker set search_path='' as $$
declare e public.equipamentos%rowtype; v_id bigint; v_cliente text; v_unidade text;
begin
  if (select auth.uid()) is null or not (private.crm_tem_permissao('osCriar') or private.crm_tem_permissao('osEditar')) then
    raise exception 'Você não possui permissão para emprestar equipamentos.' using errcode='42501';
  end if;
  if nullif(btrim(p_responsavel_nome),'') is null then raise exception 'Informe o responsável pelo equipamento.'; end if;
  select * into e from public.equipamentos where id=p_equipamento_id for update;
  if not found then raise exception 'Equipamento não encontrado.'; end if;
  if e.proprietario_tipo <> 'Help' then raise exception 'Somente máquinas da Help podem ser emprestadas como reserva.'; end if;
  if e.status <> 'Disponível no almoxarifado' then raise exception 'A máquina precisa estar disponível no almoxarifado antes do empréstimo.'; end if;
  if e.emprestado or exists(select 1 from public.equipamento_emprestimos where equipamento_id=e.id and status in ('Ativo','Aguardando devolução')) then raise exception 'Este equipamento já possui empréstimo ativo.'; end if;
  select nome into v_cliente from public.clientes where id=p_cliente_id;
  if v_cliente is null then raise exception 'Cliente não encontrado.'; end if;
  select nome into v_unidade from public.cliente_unidades where id=p_unidade_id and cliente_id=p_cliente_id and ativo;
  insert into public.equipamento_emprestimos(equipamento_id,cliente_id,unidade_id,os_id,responsavel_nome,motivo,previsao_devolucao,condicao_saida,acessorios_saida,observacoes,criado_por)
  values(e.id,p_cliente_id,p_unidade_id,p_os_id,btrim(p_responsavel_nome),coalesce(btrim(p_motivo),''),p_previsao_devolucao,coalesce(nullif(btrim(p_condicao_saida),''),e.condicao),coalesce(btrim(p_acessorios_saida),''),coalesce(btrim(p_observacoes),''),(select auth.uid()))
  returning id into v_id;
  update public.equipamentos set cliente_id=p_cliente_id,cliente_nome=v_cliente,unidade_id=p_unidade_id,status='Emprestado',emprestado=true,localizacao=v_cliente||coalesce(' · '||nullif(v_unidade,''),''),responsavel_nome=btrim(p_responsavel_nome),condicao=coalesce(nullif(btrim(p_condicao_saida),''),e.condicao),acessorios=coalesce(btrim(p_acessorios_saida),''),atualizado_em=now() where id=e.id;
  insert into public.equipamento_movimentacoes(equipamento_id,emprestimo_id,cliente_id,unidade_id,os_id,tipo,origem,destino,status_anterior,status_novo,responsavel_nome,condicao,acessorios,descricao,usuario_id)
  values(e.id,v_id,p_cliente_id,p_unidade_id,p_os_id,'Empréstimo',coalesce(nullif(e.localizacao,''),'Almoxarifado Help'),v_cliente||coalesce(' · '||nullif(v_unidade,''),''),e.status,'Emprestado',btrim(p_responsavel_nome),coalesce(nullif(btrim(p_condicao_saida),''),e.condicao),coalesce(btrim(p_acessorios_saida),''),coalesce(btrim(p_motivo),''),(select auth.uid()));
  return v_id;
end $$;

create or replace function public.devolver_emprestimo_equipamento(
  p_emprestimo_id bigint, p_condicao_retorno text, p_acessorios_retorno text,
  p_observacoes text, p_local_retorno text
)
returns bigint language plpgsql security invoker set search_path='' as $$
declare em public.equipamento_emprestimos%rowtype; e public.equipamentos%rowtype;
begin
  if (select auth.uid()) is null or not private.crm_tem_permissao('osEditar') then
    raise exception 'Você não possui permissão para receber devoluções.' using errcode='42501';
  end if;
  select * into em from public.equipamento_emprestimos where id=p_emprestimo_id and status in ('Ativo','Aguardando devolução') for update;
  if not found then raise exception 'Empréstimo ativo não encontrado.'; end if;
  select * into e from public.equipamentos where id=em.equipamento_id for update;
  update public.equipamento_emprestimos set status='Devolvido',devolvido_em=now(),devolvido_por=(select auth.uid()),condicao_retorno=coalesce(btrim(p_condicao_retorno),''),acessorios_retorno=coalesce(btrim(p_acessorios_retorno),''),observacoes=concat_ws(E'\n',nullif(observacoes,''),nullif(btrim(p_observacoes),'')),atualizado_em=now() where id=em.id;
  update public.equipamentos set cliente_id=null,cliente_nome='Estoque interno',unidade_id=null,status='Disponível no almoxarifado',emprestado=false,localizacao=coalesce(nullif(btrim(p_local_retorno),''),'Almoxarifado Help'),responsavel_nome='',condicao=coalesce(nullif(btrim(p_condicao_retorno),''),condicao),acessorios=coalesce(btrim(p_acessorios_retorno),''),atualizado_em=now() where id=e.id;
  insert into public.equipamento_movimentacoes(equipamento_id,emprestimo_id,cliente_id,unidade_id,os_id,tipo,origem,destino,status_anterior,status_novo,condicao,acessorios,descricao,usuario_id)
  values(e.id,em.id,em.cliente_id,em.unidade_id,em.os_id,'Devolução',e.localizacao,coalesce(nullif(btrim(p_local_retorno),''),'Almoxarifado Help'),e.status,'Disponível no almoxarifado',coalesce(btrim(p_condicao_retorno),''),coalesce(btrim(p_acessorios_retorno),''),coalesce(btrim(p_observacoes),''),(select auth.uid()));
  return em.id;
end $$;

