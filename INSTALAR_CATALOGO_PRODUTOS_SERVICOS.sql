create or replace function public.cancelar_financeiro_recorrencia(p_recorrencia_id bigint)
returns table (recorrencia_cancelada boolean, lancamentos_cancelados bigint)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_lancamentos bigint := 0;
begin
  if (select auth.uid()) is null or not private.crm_tem_permissao('financeiroExcluir') then
    raise exception 'Você não possui permissão para cancelar recorrências.' using errcode = '42501';
  end if;

  update public.financeiro_recorrencias
     set ativa = false,
         cancelada_em = now(),
         cancelado_por = (select auth.uid()),
         atualizado_em = now()
   where id = p_recorrencia_id;

  if not found then
    return query select false, 0::bigint;
    return;
  end if;

  update public.financeiro_lancamentos
     set status = 'Cancelado',
         atualizado_em = now()
   where recorrencia_id = p_recorrencia_id
     and status = 'Pendente';
  get diagnostics v_lancamentos = row_count;

  return query select true, v_lancamentos;
end;
$$;

revoke all on function public.cancelar_financeiro_recorrencia(bigint) from public, anon;
grant execute on function public.cancelar_financeiro_recorrencia(bigint) to authenticated;
