create table if not exists public.catalogo_itens (
  id bigint generated by default as identity primary key,
  tipo text not null,
  codigo text not null,
  descricao text not null,
  categoria text not null default '',
  unidade text not null default 'UN',
  custo numeric(14,2) not null default 0,
  preco_venda numeric(14,2) not null default 0,
  observacoes text not null default '',
  ativo boolean not null default true,
  criado_por uuid default auth.uid(),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint catalogo_itens_tipo_check check (tipo in ('Produto','Serviço')),
  constraint catalogo_itens_codigo_key unique (codigo),
  constraint catalogo_itens_valores_check check (custo >= 0 and preco_venda >= 0)
);

create index if not exists catalogo_itens_tipo_ativo_idx on public.catalogo_itens (tipo, ativo);
create index if not exists catalogo_itens_descricao_idx on public.catalogo_itens (descricao);
alter table public.catalogo_itens enable row level security;
grant select, insert, update, delete on public.catalogo_itens to authenticated;
grant usage, select on sequence public.catalogo_itens_id_seq to authenticated;

