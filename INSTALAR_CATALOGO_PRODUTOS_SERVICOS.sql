create policy "Equipe cria catalogo" on public.catalogo_itens for insert to authenticated
with check (((select private.crm_tem_permissao('crm')) or (select private.crm_tem_permissao('osCriar')) or (select private.crm_tem_permissao('osEditar'))) and criado_por = (select auth.uid()));

drop policy if exists "Equipe atualiza catalogo" on public.catalogo_itens;
create policy "Equipe atualiza catalogo" on public.catalogo_itens for update to authenticated
using ((select private.crm_tem_permissao('crm')) or (select private.crm_tem_permissao('osCriar')) or (select private.crm_tem_permissao('osEditar')))
with check ((select private.crm_tem_permissao('crm')) or (select private.crm_tem_permissao('osCriar')) or (select private.crm_tem_permissao('osEditar')));

drop policy if exists "Equipe exclui catalogo" on public.catalogo_itens;
create policy "Equipe exclui catalogo" on public.catalogo_itens for delete to authenticated
using ((select private.crm_tem_permissao('crm')) or (select private.crm_tem_permissao('osExcluir')));

