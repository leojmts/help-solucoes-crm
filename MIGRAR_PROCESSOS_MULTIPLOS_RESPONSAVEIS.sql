-- Processos internos: múltiplos responsáveis, checklist colaborativo e auditoria.
-- Migração idempotente. Mantém processos_internos.responsavel_nome e checklist
-- sincronizados como campos legados para compatibilidade com integrações antigas.

begin;

create table if not exists public.processo_responsaveis (
  processo_id uuid not null references public.processos_internos(id) on delete cascade,
  usuario_id uuid not null references public.perfis_usuarios(user_id) on delete cascade,
  atribuido_por uuid references auth.users(id) on delete set null default auth.uid(),
  atribuido_em timestamptz not null default now(),
  primary key (processo_id, usuario_id)
);

create index if not exists processo_responsaveis_usuario_idx
  on public.processo_responsaveis(usuario_id, processo_id);
create index if not exists processo_responsaveis_atribuido_por_idx
  on public.processo_responsaveis(atribuido_por);

create table if not exists public.processo_checklist_itens (
  id uuid primary key default gen_random_uuid(),
  processo_id uuid not null references public.processos_internos(id) on delete cascade,
  ordem integer not null check (ordem >= 0),
  texto text not null check (char_length(btrim(texto)) between 1 and 500),
  concluido boolean not null default false,
  marcado_por uuid references auth.users(id) on delete set null,
  marcado_por_nome text,
  marcado_em timestamptz,
  alterado_por uuid references auth.users(id) on delete set null,
  alterado_por_nome text,
  alterado_em timestamptz,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (processo_id, ordem)
);

create index if not exists processo_checklist_itens_processo_idx
  on public.processo_checklist_itens(processo_id, ordem);
create index if not exists processo_checklist_itens_marcado_por_idx
  on public.processo_checklist_itens(marcado_por);
create index if not exists processo_checklist_itens_alterado_por_idx
  on public.processo_checklist_itens(alterado_por);

create table if not exists public.processo_checklist_historico (
  id bigint generated by default as identity primary key,
  processo_id uuid not null references public.processos_internos(id) on delete cascade,
  item_id uuid references public.processo_checklist_itens(id) on delete set null,
  item_texto text not null,
  acao text not null check (acao in ('marcou', 'desmarcou')),
  usuario_id uuid references auth.users(id) on delete set null,
  usuario_nome text not null,
  ocorrido_em timestamptz not null default now()
);

create index if not exists processo_checklist_historico_processo_idx
  on public.processo_checklist_historico(processo_id, ocorrido_em desc);
create index if not exists processo_checklist_historico_item_idx
  on public.processo_checklist_historico(item_id);
create index if not exists processo_checklist_historico_usuario_idx
  on public.processo_checklist_historico(usuario_id, ocorrido_em desc);

-- Preserva os responsáveis antigos, associando pelo nome já salvo no processo.
insert into public.processo_responsaveis (processo_id, usuario_id, atribuido_por, atribuido_em)
select p.id, u.user_id, p.criado_por, p.criado_em
from public.processos_internos p
join public.perfis_usuarios u
  on lower(btrim(u.nome)) = lower(btrim(p.responsavel_nome))
where u.ativo
on conflict (processo_id, usuario_id) do nothing;

-- Se um nome legado não tiver correspondência, mantém o processo utilizável pelo criador ativo.
insert into public.processo_responsaveis (processo_id, usuario_id, atribuido_por, atribuido_em)
select p.id, p.criado_por, p.criado_por, p.criado_em
from public.processos_internos p
join public.perfis_usuarios u on u.user_id = p.criado_por and u.ativo
where not exists (
  select 1 from public.processo_responsaveis r where r.processo_id = p.id
)
on conflict (processo_id, usuario_id) do nothing;

-- Converte o JSON legado em itens relacionais sem apagar o campo antigo.
insert into public.processo_checklist_itens (processo_id, ordem, texto, concluido)
select p.id,
       (item.ordinality - 1)::integer,
       left(btrim(coalesce(item.valor->>'texto', '')), 500),
       coalesce((item.valor->>'concluido')::boolean, false)
from public.processos_internos p
cross join lateral jsonb_array_elements(coalesce(p.checklist, '[]'::jsonb))
  with ordinality as item(valor, ordinality)
where btrim(coalesce(item.valor->>'texto', '')) <> ''
  and not exists (
    select 1 from public.processo_checklist_itens ci where ci.processo_id = p.id
  )
on conflict (processo_id, ordem) do nothing;

create or replace function private.listar_usuarios_ativos_processo()
returns table(user_id uuid, nome text, perfil text)
language sql
stable
security definer
set search_path = ''
as $$
  select p.user_id, coalesce(nullif(btrim(p.nome), ''), split_part(p.email, '@', 1)), p.perfil
  from public.perfis_usuarios p
  where p.ativo
    and (select auth.uid()) is not null
    and private.crm_usuario_ativo()
  order by 2;
$$;

revoke all on function private.listar_usuarios_ativos_processo() from public, anon;
grant execute on function private.listar_usuarios_ativos_processo() to authenticated;

