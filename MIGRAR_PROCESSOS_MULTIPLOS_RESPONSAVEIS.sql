$$;

revoke all on function public.listar_usuarios_ativos_processo() from public, anon;
grant execute on function public.listar_usuarios_ativos_processo() to authenticated;

create or replace function private.crm_usuario_alvo_ativo(p_usuario_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select (select auth.uid()) is not null
    and private.crm_usuario_ativo()
    and exists (
      select 1 from public.perfis_usuarios p
      where p.user_id = p_usuario_id and p.ativo
    );
$$;

revoke all on function private.crm_usuario_alvo_ativo(uuid) from public, anon, authenticated;

create or replace function private.sincronizar_responsavel_nome_processo()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_processo_id uuid := coalesce(new.processo_id, old.processo_id);
  v_nomes text;
begin
  select string_agg(
           coalesce(nullif(btrim(p.nome), ''), split_part(p.email, '@', 1)),
           ' • ' order by coalesce(nullif(btrim(p.nome), ''), split_part(p.email, '@', 1))
         )
    into v_nomes
  from public.processo_responsaveis r
  join public.perfis_usuarios p on p.user_id = r.usuario_id
  where r.processo_id = v_processo_id;

  if v_nomes is not null then
    update public.processos_internos
       set responsavel_nome = v_nomes,
           atualizado_em = now()
     where id = v_processo_id;
  end if;
  return coalesce(new, old);
end;
$$;

revoke all on function private.sincronizar_responsavel_nome_processo() from public, anon, authenticated;
drop trigger if exists trg_sincronizar_responsavel_nome_processo on public.processo_responsaveis;
create trigger trg_sincronizar_responsavel_nome_processo
after insert or delete on public.processo_responsaveis
for each row execute function private.sincronizar_responsavel_nome_processo();

create or replace function private.registrar_alteracao_checklist_processo()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_usuario uuid := (select auth.uid());
  v_nome text;
begin
  if old.concluido is not distinct from new.concluido then
    new.atualizado_em := now();
    return new;
  end if;

  if v_usuario is null or not private.crm_usuario_ativo() then
    raise exception 'Usuário sem permissão para alterar o checklist.' using errcode = '42501';
  end if;

  if not private.crm_tem_permissao('usuarios') and not exists (
    select 1
    from public.processo_responsaveis r
    where r.processo_id = new.processo_id and r.usuario_id = v_usuario
  ) then
    raise exception 'Somente responsáveis ou administradores podem alterar o checklist.' using errcode = '42501';
  end if;

  select coalesce(nullif(btrim(p.nome), ''), split_part(p.email, '@', 1))
    into v_nome
  from public.perfis_usuarios p
  where p.user_id = v_usuario and p.ativo;

  if v_nome is null then
    raise exception 'Perfil ativo não encontrado.' using errcode = '42501';
  end if;

  new.alterado_por := v_usuario;
  new.alterado_por_nome := v_nome;
  new.alterado_em := now();
  new.atualizado_em := now();

  if new.concluido then
    new.marcado_por := v_usuario;
    new.marcado_por_nome := v_nome;
    new.marcado_em := now();
  else
    new.marcado_por := null;
    new.marcado_por_nome := null;
    new.marcado_em := null;
  end if;

  insert into public.processo_checklist_historico
    (processo_id, item_id, item_texto, acao, usuario_id, usuario_nome, ocorrido_em)
  values
    (new.processo_id, new.id, new.texto,
     case when new.concluido then 'marcou' else 'desmarcou' end,
     v_usuario, v_nome, now());

  return new;
end;
$$;

revoke all on function private.registrar_alteracao_checklist_processo() from public, anon, authenticated;
drop trigger if exists trg_registrar_alteracao_checklist_processo on public.processo_checklist_itens;
create trigger trg_registrar_alteracao_checklist_processo
before update on public.processo_checklist_itens
for each row execute function private.registrar_alteracao_checklist_processo();

create or replace function private.sincronizar_checklist_legado_processo()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_processo_id uuid := coalesce(new.processo_id, old.processo_id);
  v_checklist jsonb;
begin
  select coalesce(
           jsonb_agg(
             jsonb_build_object(
               'id', i.id,
               'texto', i.texto,
               'concluido', i.concluido,
               'marcado_por', i.marcado_por,
               'marcado_por_nome', i.marcado_por_nome,
               'marcado_em', i.marcado_em
             ) order by i.ordem
           ),
           '[]'::jsonb
         )
    into v_checklist
  from public.processo_checklist_itens i
  where i.processo_id = v_processo_id;

  update public.processos_internos
     set checklist = v_checklist,
         atualizado_em = now()
   where id = v_processo_id;
  return coalesce(new, old);
end;
$$;

revoke all on function private.sincronizar_checklist_legado_processo() from public, anon, authenticated;
drop trigger if exists trg_sincronizar_checklist_legado_processo on public.processo_checklist_itens;
create trigger trg_sincronizar_checklist_legado_processo
after insert or update or delete on public.processo_checklist_itens
for each row execute function private.sincronizar_checklist_legado_processo();

